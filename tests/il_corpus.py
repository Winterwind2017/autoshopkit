"""Compile a corpus of instruction-list snippets and record what the app accepts.

Each snippet is written into MAIN through the instruction-list channel, converted
and compiled; the compile summary and any error line are recorded.  Results are
written to docs/IL-results.md so the documented dialect always matches evidence.

Run:  python tools/il_corpus.py
"""
import ctypes
import json
import os
import shutil
import sys
import time

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src"))

try:
    ctypes.windll.shcore.SetProcessDpiAwareness(2)
except Exception:
    pass

from autoshopkit.app import AutoShop

SRC = _template.require_template("il_corpus.py")
WORK = r"D:\bililive\autoshopkit\sandbox\ilcorpus"
OUT_MD = r"D:\bililive\autoshopkit\docs\IL-results.md"

CORPUS = [
    ("contact + coil", "LD X0\nOUT Y0\n"),
    ("series", "LD X0\nAND X1\nOUT Y0\n"),
    ("parallel", "LD X0\nOR X1\nOUT Y0\n"),
    ("timer", "LD X0\nOUT T0 K10\n"),
    ("counter", "LD X0\nOUT C0 K5\n"),
    ("move", "LD X0\nMOV K1 D0\n"),
    ("double move", "LD X0\nDMOV K10 D0\n"),
    ("set / reset", "LD X0\nSET Y0\nLD X1\nRST Y0\n"),
    ("compare contact", "LD> D0 K5\nOUT Y1\n"),
    ("stack (MPS/MRD/MPP)", "LD X0\nMPS\nAND X1\nOUT Y0\nMRD\nAND X2\nOUT Y1\nMPP\nOUT Y2\n"),
    ("pulse", "LD X0\nPLS M0\n"),
    ("zone reset", "LD X0\nZRST M0 M10\n"),
    ("master control", "LD X0\nMC N0 M100\nLD X1\nOUT Y0\nMCR N0\n"),
    ("for / next", "LD X0\nFOR K5\nINC D0\nNEXT\n"),
    ("jump (CJ + LBL)", "LD X0\nCJ P0\nLD X1\nOUT Y0\nLBL P0\n"),
    ("label only (LBL)", "LD X0\nOUT Y0\nLBL P1\n"),
    ("jump to end (CJEND)", "LD X0\nCJEND\n"),
    ("call subprogram", "LD X0\nCALL SBR_001\nLD X1\nOUT Y0\n"),
    ("sequential (STL)", "STL S0\nLD X0\nSET S1\nRET\n"),
    ("compare block (CMP)", "LD X0\nCMP K1 K5 M10\n"),
    ("zone compare (ZCP)", "LD X0\nZCP K1 K5 D0 M10\n"),
    ("exchange (XCH)", "LD X0\nXCH D0 D1\n"),
    ("byte swap (SWAP)", "LD X0\nSWAP D0\n"),
    ("negate (NEG)", "LD X0\nNEG D0\n"),
    ("block move (BMOV)", "LD X0\nBMOV D0 D10 K5\n"),
    ("two networks", "LD X0\nOUT Y0\nLD X1\nOUT Y1\n"),
    ("networks + comments", "//net one\nLD X0\nOUT Y0\n//net two\nLD X1\nOUT Y1\n"),
]


def main():
    app = AutoShop.attach()
    if app:
        app.close()
        time.sleep(2)
    if os.path.isdir(WORK):
        shutil.rmtree(WORK)
    shutil.copytree(SRC, WORK)
    hcp = [f for f in os.listdir(WORK) if f.lower().endswith(".hcp")][0]
    app = AutoShop.launch(os.path.join(WORK, hcp), wait=90, timeout_title="ilcorpus")
    time.sleep(1)
    app.activate_document("MAIN")
    app.view_il()

    rows = []
    for name, text in CORPUS:
        app.set_program_il(text)
        time.sleep(0.5)
        readback = (app.program_il() or "").replace("\t", " ").strip()
        app.view_ladder()
        time.sleep(0.4)
        ok, lines = app.compile()
        summary = next((l for l in lines if "统计 -" in l), "")
        errors = [l.strip() for l in lines if l.strip().startswith("错误")]
        rows.append({"name": name, "source": text, "compiles": bool(ok),
                     "summary": summary, "errors": errors, "readback": readback})
        print("%-22s %-5s %s" % (name, ok, summary or errors[:2]), flush=True)
        app.view_il()
        time.sleep(0.4)

    app.close()

    ok_count = sum(1 for r in rows if r["compiles"])
    lines = ["# Instruction-list corpus: measured results", "",
             "Generated by `tools/il_corpus.py` on %s against AutoShop V4.11.0.5 "
             "(H3U project, MAIN program)." % time.strftime("%Y-%m-%d %H:%M"),
             "", "**%d/%d snippets compile with no error.**" % (ok_count, len(rows)), "",
             "| snippet | compiles | AutoShop's answer |", "| --- | --- | --- |"]
    for r in rows:
        answer = r["summary"] or "; ".join(r["errors"][:2])
        lines.append("| %s | %s | `%s` |" % (
            r["name"], "yes" if r["compiles"] else "**no**", answer.replace("|", "/")))
    lines += ["", "## Sources", ""]
    for r in rows:
        lines += ["### %s" % r["name"], "", "```", r["source"].rstrip(), "```", "",
                  "- app form after conversion: `%s`" % r["readback"].split("\n")[0][:60],
                  "- result: %s" % ("compiles, " + r["summary"] if r["compiles"]
                                    else "rejected: " + "; ".join(r["errors"][:3])), ""]
    with open(OUT_MD, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    with open(os.path.join(os.path.dirname(OUT_MD), "IL-results.json"), "w", encoding="utf-8") as fh:
        json.dump(rows, fh, ensure_ascii=False, indent=1)

    print("\n%d/%d compile  ->  %s" % (ok_count, len(rows), OUT_MD))
    return 0 if ok_count == len(rows) else 1


if __name__ == "__main__":
    sys.exit(main())
